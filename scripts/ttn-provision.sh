#!/usr/bin/env bash
# Create the TTN application and OTAA end device, install the payload formatter
# and write firmware/secrets.h with the generated credentials.
set -euo pipefail

APP_ID="${APP_ID:-xiao-temperature}"
DEVICE_ID="${DEVICE_ID:-xiao-temperature-01}"
TTN_HOST="${TTN_HOST:-eu1.cloud.thethings.network}"
FREQUENCY_PLAN="${FREQUENCY_PLAN:-EU_863_870_TTN}"

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
SECRETS="$ROOT/firmware/secrets.h"
FORMATTER="$ROOT/firmware/ttn_payload_formatter.js"

die() { echo "error: $*" >&2; exit 1; }
cli() { ttn-lw-cli "$@" 2> >(grep -Ev '^(INFO|WARN)' >&2); }

command -v ttn-lw-cli >/dev/null || die "ttn-lw-cli not found (run: make setup)"
command -v openssl >/dev/null || die "openssl not found"
command -v jq >/dev/null || die "jq not found"

if [ -e "$SECRETS" ] && [ "${FORCE:-0}" != 1 ]; then
  die "$SECRETS already exists. It holds the credentials of a registered device; run with FORCE=1 to back it up and replace it."
fi

cli applications list >/dev/null 2>&1 || die "not logged in to TTN (run: make ttn-login)"

if cli end-devices get "$APP_ID" "$DEVICE_ID" >/dev/null 2>&1; then
  die "device $DEVICE_ID already exists in $APP_ID; choose another DEVICE_ID"
fi

if cli applications get "$APP_ID" >/dev/null 2>&1; then
  echo "Application $APP_ID exists."
else
  echo "Creating application $APP_ID..."
  USER_ID="$(cli auth-info | jq -r '.oauth_access_token.user_ids.user_id')"
  [ -n "$USER_ID" ] && [ "$USER_ID" != null ] || die "could not determine TTN user ID (log in with a user account)"
  cli applications create "$APP_ID" --name "$APP_ID" --user-id "$USER_ID" >/dev/null
fi

echo "Installing uplink payload formatter..."
cli applications link set "$APP_ID" \
  --default-formatters.up-formatter FORMATTER_JAVASCRIPT \
  --default-formatters.up-formatter-parameter-local-file "$FORMATTER" >/dev/null

JOIN_EUI="0000000000000000"
DEV_EUI="$(openssl rand -hex 8 | tr 'a-f' 'A-F')"
APP_KEY="$(openssl rand -hex 16 | tr 'a-f' 'A-F')"
NWK_KEY="$(openssl rand -hex 16 | tr 'a-f' 'A-F')"

echo "Registering end device $DEVICE_ID..."
cli end-devices create "$APP_ID" "$DEVICE_ID" \
  --frequency-plan-id "$FREQUENCY_PLAN" \
  --lorawan-version 1.1.0 \
  --lorawan-phy-version 1.1.0-b \
  --supports-join \
  --join-eui "$JOIN_EUI" \
  --dev-eui "$DEV_EUI" \
  --root-keys.app-key.key "$APP_KEY" \
  --root-keys.nwk-key.key "$NWK_KEY" \
  --network-server-address "$TTN_HOST" \
  --application-server-address "$TTN_HOST" \
  --join-server-address "$TTN_HOST" >/dev/null

if [ -e "$SECRETS" ]; then
  cp "$SECRETS" "$SECRETS.bak.$(date +%Y%m%d%H%M%S)"
fi

umask 077
cat > "$SECRETS" <<EOF
#ifndef XIAO_TEMPERATURE_SECRETS_H
#define XIAO_TEMPERATURE_SECRETS_H

#include <Arduino.h>

// Generated by scripts/ttn-provision.sh for $APP_ID / $DEVICE_ID.
// Keep this file out of version control.
uint64_t joinEUI = 0x$JOIN_EUI;
uint64_t devEUI = 0x$DEV_EUI;

const char appKeyHex[] = "$APP_KEY";
const char nwkKeyHex[] = "$NWK_KEY";

#endif
EOF

echo "Wrote $SECRETS"
echo "Done: application $APP_ID, device $DEVICE_ID on $TTN_HOST."
